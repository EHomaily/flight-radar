_extra_cities: dict[str, str] = {}


def load_extra_cities(path: Path) -> None:
    """أسماء إضافية (من قاعدة مدن Travelpayouts) تُحفظ محلياً."""
    if path.exists():
        try:
            _extra_cities.update(json.loads(path.read_text(encoding="utf-8")))
        except (OSError, ValueError):
            pass


def city(code: str | None) -> str:
    if not code:
        return "؟"
    return CITIES_AR.get(code) or _extra_cities.get(code) or code


def airline(code: str | None) -> str:
    if not code:
        return ""
    return AIRLINES_AR.get(code, code)


def fmt_date(d: dt.date | str | None, with_weekday: bool = True) -> str:
    if not d:
        return ""
    if isinstance(d, str):
        d = dt.date.fromisoformat(d[:10])
    s = f"{d.day} {MONTHS_AR[d.month - 1]} {d.year}"
    return f"{WEEKDAYS_AR[d.weekday()]} {s}" if with_weekday else s


def fmt_month(m: str) -> str:
    y, mo = m.split("-")
    return f"{MONTHS_AR[int(mo) - 1]} {y}"


def fmt_price(p: float | None, currency: str) -> str:
    if p is None:
        return "—"
    return f"{round(p):,} {CURRENCY_AR.get(currency, currency)}"


def stops_label(n: int | None) -> str:
    if n is None:
        return ""
    return {0: "مباشر", 1: "توقف واحد", 2: "توقفان"}.get(n, f"{n} توقفات")
